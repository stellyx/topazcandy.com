import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {buildModel,routeBetween,sourceSegments} from '../qhcf/eastern-road-preview.mjs';

const source=JSON.parse(readFileSync(new URL('../qhcf/data/areas/the-eastern-road.json',import.meta.url)));
const model=buildModel(source);
const segments=sourceSegments(source);
assert.equal(segments.length,source.lines.join('').split('').filter(c=>c==='-'||c==='|').length);
for(const {row,column,glyph} of segments)assert.equal(source.lines[row-1][column-1],glyph);
const at=(row,column)=>segments.some(s=>s.row===row&&s.column===column);
for(const [row,column] of [[2,67],[3,67],[4,67],[4,75],[6,46],[7,46],[6,57],[8,57],[15,38],[8,68],[9,68],[15,35]])assert.equal(at(row,column),false,`Unsupported road at r${row}c${column}`);
for(const [row,column] of [[3,9],[4,9],[6,23],[15,24],[17,24],[17,38],[19,45],[6,68]])assert.equal(at(row,column),true,`Missing source pipe at r${row}c${column}`);
assert.equal(model.nodes.filter(n=>n.kind==='plus').length,9);
assert.equal(model.nodes.filter(n=>n.kind==='plus').length,source.lines.join('').split('+').length-1);
const id=s=>`eastern.map.${s}`;
const outbound=routeBetween(model,id('c'),id('east-one'));
assert.equal(outbound.moves,12);
assert.deepEqual(outbound.runs,['7e','5e']);
assert.equal(outbound.commands.join(';;'),Array(12).fill('e').join(';;'));
const inbound=routeBetween(model,id('east-one'),id('c'));
assert.equal(inbound.moves,12);
assert.deepEqual(inbound.runs,['5w','7w']);
assert.equal(inbound.commands.join(';;'),Array(12).fill('w').join(';;'));
assert.equal(routeBetween(model,id('r5c58'),id('c')),null);
assert.equal(routeBetween(model,id('south-one'),id('east-one')),null);
assert.equal(routeBetween(model,id('c'),id('c')).moves,0);
for(const area of model.areas.filter(a=>a.slug))assert.ok(existsSync(new URL(`../qhcf/areas/${area.slug}.html`,import.meta.url)),area.name);
assert.equal(model.areas.find(a=>a.name==='Galadon').preview,'/qhcf/galadon-preview.html');
assert.ok(existsSync(new URL('../qhcf/galadon-preview.html',import.meta.url)));
const page=readFileSync(new URL('../qhcf/eastern-road-preview.html',import.meta.url),'utf8');
for(const id of ['map','viewport','from','to','flip','copy','commands','area-select','fit-route'])assert.ok(page.includes(`id="${id}"`),id);
assert.ok(page.includes('href="/qhcf/world-map.html"'));
assert.ok(page.includes('href="/qhcf/areas/the-eastern-road.html"'));
assert.ok(page.includes('Galadon handoff unresolved'));
assert.ok(page.includes('Routes here never add a Galadon step'));
assert.ok(page.includes('e;;e;;w'));
assert.ok(page.includes('id="copy-feedback" role="status"'));
const script=readFileSync(new URL('../qhcf/eastern-road-preview.mjs',import.meta.url),'utf8');
assert.ok(script.includes('for(const {row,column,glyph} of sourceSegments(source))'));
assert.ok(!script.includes('line(5,8,84)'));
assert.ok(!script.includes('[[9,2,5]'));
assert.ok(script.includes('Clipboard write reported success. Paste to confirm'));
assert.ok(script.includes('Clipboard access unavailable. Commands selected'));
console.log('Eastern Road source, counts, reverse routes, unresolved branches, links, and controls passed.');
